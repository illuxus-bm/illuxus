#!/usr/bin/env node
/**
 * Writes supabase/install.rds.sql: supabase/install.sql adapted for AWS RDS
 * (or any plain Postgres), to run after scripts/rds/bootstrap.sql.
 *
 *   node scripts/rds/build-rds-install.mjs
 *
 * What changes, and only this:
 *   - pg_net and supabase_vault (Supabase-only) are not created; bootstrap.sql
 *     provides net.http_post as a queue instead.
 *   - pg_cron and pg_stat_statements are created only when the server offers
 *     them (RDS: add them to shared_preload_libraries in the parameter
 *     group). Without pg_cron the scheduled job is skipped with a notice;
 *     run `SELECT public.communications_run_scheduled()` from a scheduler.
 *   - The supabase_realtime publication is created if missing, so the
 *     statements adding tables to it still apply (logical replication on RDS
 *     needs rds.logical_replication = 1 to use it).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const src = readFileSync(resolve(ROOT, "supabase/install.sql"), "utf8").replace(/\r\n/g, "\n");

const optionalExtension = (name, schema) => `DO $rds$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = '${name}') THEN
    EXECUTE 'CREATE EXTENSION IF NOT EXISTS "${name}" WITH SCHEMA "${schema}"';
  ELSE
    RAISE NOTICE 'illuxus: extension ${name} is not available here; skipped';
  END IF;
END $rds$;`;

let out = src
  .replace(/^CREATE EXTENSION IF NOT EXISTS "pg_net" WITH SCHEMA "public";$/m, "-- pg_net: not on RDS; net.http_post comes from scripts/rds/bootstrap.sql")
  .replace(/^CREATE EXTENSION IF NOT EXISTS "supabase_vault" WITH SCHEMA "vault";$/m, "-- supabase_vault: Supabase-only; not used by illuxus code")
  .replace(/^CREATE EXTENSION IF NOT EXISTS "pg_cron" WITH SCHEMA "pg_catalog";$/m, optionalExtension("pg_cron", "pg_catalog"))
  .replace(/^CREATE EXTENSION IF NOT EXISTS "pg_stat_statements" WITH SCHEMA "extensions";$/m, optionalExtension("pg_stat_statements", "extensions"));

// cron.schedule(...) only where pg_cron exists.
out = out.replace(/^SELECT cron\.schedule\((.*)\);$/gm, (_m, args) => `DO $rds$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    PERFORM cron.schedule(${args});
  ELSE
    RAISE NOTICE 'illuxus: pg_cron not installed; schedule this job elsewhere: %', ${JSON.stringify(args).replace(/'/g, "''").replace(/^"|"$/g, "'")};
  END IF;
END $rds$;`);

// The realtime publication must exist before tables are added to it.
const firstPublication = out.indexOf('ALTER PUBLICATION "supabase_realtime"');
if (firstPublication >= 0) {
  out = out.slice(0, firstPublication) + `DO $rds$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    CREATE PUBLICATION supabase_realtime;
  END IF;
END $rds$;

` + out.slice(firstPublication);
}

const header = `-- GENERATED by scripts/rds/build-rds-install.mjs from supabase/install.sql. Do not edit.
-- Run after scripts/rds/bootstrap.sql on AWS RDS (docs/PRISMA_MIGRATION.md).
`;
writeFileSync(resolve(ROOT, "supabase/install.rds.sql"), header + out);
console.log("wrote supabase/install.rds.sql");
