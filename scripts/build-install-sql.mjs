#!/usr/bin/env node
// Builds supabase/install.sql: ONE file that sets up a brand-new Supabase
// project with the whole illuxus + illuxus-venue database (both apps share
// it), in one transaction.
//
// Inputs (regenerate them from production when the schema changes):
//   supabase/prod_schema.sql  npx supabase db dump --linked -f supabase/prod_schema.sql
//   supabase/install/seed.sql reference data only (see that file's header)
//
// The parts a schema dump leaves out — triggers on auth.users, storage
// buckets and policies, cron jobs — are declared below, from production
// (checked 2026-11-08) and the two repos' migrations.
//
//   node scripts/build-install-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8").replace(/\r\n/g, "\n");

const schema = read("supabase/prod_schema.sql");
const seed = read("supabase/install/seed.sql");

const count = (re) => (schema.match(re) || []).length;
const expected = {
  tables: count(/^CREATE TABLE IF NOT EXISTS "public"\./gm),
  functions: count(/^CREATE OR REPLACE FUNCTION "public"\./gm),
  policies: count(/^CREATE POLICY /gm),
  triggers: count(/^CREATE OR REPLACE TRIGGER |^CREATE TRIGGER /gm),
  views: count(/^CREATE OR REPLACE VIEW "public"\.|^CREATE VIEW "public"\./gm),
};

// The dump's own session settings and transaction-unsafe lines are handled
// by the wrapper below.
const schemaBody = schema
  .replace(/^RESET ALL;\s*$/gm, "")
  .replace(/^SET transaction_timeout = 0;\s*$/gm, "");

const out = `-- ═══════════════════════════════════════════════════════════════════════════════
-- illuxus — complete database install (illuxus web/app + illuxus-venue)
--
-- GENERATED by scripts/build-install-sql.mjs — do not edit by hand.
-- Source: production schema dump (supabase/prod_schema.sql) + the parts a
-- dump leaves out (auth triggers, storage, cron) + reference data.
--
-- WHAT IT IS FOR
--   Setting up a NEW, EMPTY Supabase project with the whole database:
--   ${expected.tables} tables, ${expected.functions} functions, ${expected.triggers} triggers,
--   ${expected.policies} row-security policies, views, grants, realtime,
--   storage buckets and policies, the scheduled job, and reference data.
--   It refuses to run on a database that already has the illuxus schema.
--
-- HOW TO RUN (one of)
--   • psql (recommended for a file this size):
--       psql "<new project's connection string>" -v ON_ERROR_STOP=1 -f supabase/install.sql
--   • Supabase Dashboard → SQL Editor → paste the whole file → Run.
--
-- It runs in ONE transaction: if anything fails, nothing is created.
--
-- AFTER IT RUNS — see supabase/install/SETUP.md (secrets, edge functions,
-- auth settings, app_settings, frontend environment variables).
-- ═══════════════════════════════════════════════════════════════════════════════

\BEGIN;

-- ── 0. Only on a new, empty project ──────────────────────────────────────────
DO $guard$
BEGIN
  IF to_regclass('public.events') IS NOT NULL OR to_regclass('public.profiles') IS NOT NULL THEN
    RAISE EXCEPTION 'This database already has the illuxus schema. install.sql is only for a NEW, empty Supabase project.';
  END IF;
  IF to_regclass('auth.users') IS NULL THEN
    RAISE EXCEPTION 'auth.users is missing: run this on a Supabase project (it provides the auth and storage schemas).';
  END IF;
END
$guard$;


-- ── Grants exactly as in production ──────────────────────────────────────────
-- A new Supabase project automatically grants every new table, function and
-- sequence in "public" to anon, authenticated and service_role. Production
-- removed those defaults (only service_role gets them), and each object's
-- grants below are production's. Without this, every object would also be
-- granted to anon / authenticated — undoing the security work (locked-down
-- functions, read-only tables, column-level grants on organizations).
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON TABLES    FROM anon, authenticated, service_role, postgres;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM anon, authenticated, service_role, postgres;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon, authenticated, service_role, postgres;
-- (Production's own service_role defaults are restored at the end of section 1.)


-- ═══════════════════════════════════════════════════════════════════════════════
-- 1. Schema: extensions, types, tables, functions, views, indexes, row
--    security, policies, grants, realtime publication (production dump)
-- ═══════════════════════════════════════════════════════════════════════════════

${schemaBody.trim()}

SELECT pg_catalog.set_config('search_path', 'public, extensions', true);


-- ═══════════════════════════════════════════════════════════════════════════════
-- 2. Triggers on auth.users (a schema dump of "public" doesn't include them)
--    on_auth_user_created       — creates the profile row at sign-up
--    on_auth_user_email_verified — attaches records once an address is proven
-- ═══════════════════════════════════════════════════════════════════════════════

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

DROP TRIGGER IF EXISTS on_auth_user_email_verified ON auth.users;
CREATE TRIGGER on_auth_user_email_verified
  AFTER UPDATE OF email_confirmed_at, email ON auth.users
  FOR EACH ROW
  WHEN (new.email IS NOT NULL AND new.email_confirmed_at IS NOT NULL
        AND (old.email_confirmed_at IS NULL OR new.email::text IS DISTINCT FROM old.email::text))
  EXECUTE FUNCTION public.handle_auth_email_verified();


-- ═══════════════════════════════════════════════════════════════════════════════
-- 3. Storage buckets and policies
--    Production had duplicate copies of some policies (made in the dashboard);
--    only one of each is created here.
-- ═══════════════════════════════════════════════════════════════════════════════

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES
  ('avatars',            'avatars',            true,  5242880,  ARRAY['image/png','image/jpeg','image/webp','image/gif']),
  ('site-assets',        'site-assets',        true,  26214400, NULL),
  ('community',          'community',          true,  26214400, NULL),
  ('webinar-recordings', 'webinar-recordings', false, NULL,     NULL),
  ('vendor-media',       'vendor-media',       true,  52428800, ARRAY['image/png','image/jpeg','image/webp','image/gif','video/mp4','video/webm','application/pdf']),
  ('venue-media',        'venue-media',        true,  52428800, ARRAY['image/jpeg','image/png','image/webp','image/gif','image/avif','image/svg+xml','application/pdf','video/mp4','video/webm','video/quicktime'])
ON CONFLICT (id) DO UPDATE
  SET public = excluded.public, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

-- avatars: anyone reads; each user writes only in their own folder (<user id>/…)
CREATE POLICY "Avatars readable" ON storage.objects FOR SELECT USING (bucket_id = 'avatars');
CREATE POLICY "Users upload avatar" ON storage.objects FOR INSERT
  WITH CHECK (bucket_id = 'avatars' AND auth.uid()::text = (storage.foldername(name))[1]);
CREATE POLICY "Users update avatar" ON storage.objects FOR UPDATE
  USING (bucket_id = 'avatars' AND auth.uid()::text = (storage.foldername(name))[1]);
CREATE POLICY "Users delete avatar" ON storage.objects FOR DELETE
  USING (bucket_id = 'avatars' AND auth.uid()::text = (storage.foldername(name))[1]);

-- site-assets: anyone reads; writes decided by folder (site_asset_writable:
-- website files → platform admins; event / org folders → their organisers)
CREATE POLICY "Public read site-assets" ON storage.objects FOR SELECT USING (bucket_id = 'site-assets');
CREATE POLICY "site-assets upload by folder" ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'site-assets' AND public.site_asset_writable(name, COALESCE(owner_id, owner::text)));
CREATE POLICY "site-assets update by folder" ON storage.objects FOR UPDATE TO authenticated
  USING      (bucket_id = 'site-assets' AND public.site_asset_writable(name, COALESCE(owner_id, owner::text)))
  WITH CHECK (bucket_id = 'site-assets' AND public.site_asset_writable(name, COALESCE(owner_id, owner::text)));
CREATE POLICY "site-assets delete by folder" ON storage.objects FOR DELETE TO authenticated
  USING (bucket_id = 'site-assets' AND public.site_asset_writable(name, COALESCE(owner_id, owner::text)));

-- community: anyone reads; only that community's members upload (<community id>/…)
CREATE POLICY "Public read community" ON storage.objects FOR SELECT USING (bucket_id = 'community');
CREATE POLICY "Members write community" ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id = 'community'
    AND split_part(name, '/', 1) ~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
    AND (public.is_community_member(auth.uid(), split_part(name, '/', 1)::uuid)
         OR public.can_moderate_community(auth.uid(), split_part(name, '/', 1)::uuid))
  );

-- webinar-recordings: private; only the server (service role) reads or writes.

-- vendor-media (illuxus-venue): anyone reads; a vendor's members write in <vendor id>/…
CREATE POLICY "vendor_media_public_read" ON storage.objects FOR SELECT USING (bucket_id = 'vendor-media');
CREATE POLICY "vendor_media_member_insert" ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'vendor-media' AND public.is_vendor_member(((storage.foldername(name))[1])::uuid));
CREATE POLICY "vendor_media_member_update" ON storage.objects FOR UPDATE TO authenticated
  USING (bucket_id = 'vendor-media' AND public.is_vendor_member(((storage.foldername(name))[1])::uuid));
CREATE POLICY "vendor_media_member_delete" ON storage.objects FOR DELETE TO authenticated
  USING (bucket_id = 'vendor-media' AND public.is_vendor_member(((storage.foldername(name))[1])::uuid));

-- venue-media (illuxus-venue): anyone reads; signed-in users upload; owners change their own
CREATE POLICY "venue_media_public_read" ON storage.objects FOR SELECT USING (bucket_id = 'venue-media');
CREATE POLICY "venue_media_auth_insert" ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'venue-media');
CREATE POLICY "venue_media_owner_update" ON storage.objects FOR UPDATE TO authenticated
  USING (bucket_id = 'venue-media' AND owner = auth.uid())
  WITH CHECK (bucket_id = 'venue-media' AND owner = auth.uid());
CREATE POLICY "venue_media_owner_delete" ON storage.objects FOR DELETE TO authenticated
  USING (bucket_id = 'venue-media' AND owner = auth.uid());


-- ═══════════════════════════════════════════════════════════════════════════════
-- 4. Scheduled job (pg_cron): send scheduled emails / WhatsApp every minute.
--    It does nothing until app_settings holds the project URL and key (SETUP.md).
-- ═══════════════════════════════════════════════════════════════════════════════

SELECT cron.schedule('communications-tick', '* * * * *', 'SELECT public.communications_run_scheduled()');


-- ═══════════════════════════════════════════════════════════════════════════════
-- 5. Reference data: plans, website content, vendor categories.
--    No user data, no secrets. (app_settings is filled in after install:
--    see SETUP.md.)
-- ═══════════════════════════════════════════════════════════════════════════════

${seed.trim()}


-- ═══════════════════════════════════════════════════════════════════════════════
-- 6. Check: everything was created
-- ═══════════════════════════════════════════════════════════════════════════════

-- The schema dump turned notices off; show the result line.
SET client_min_messages = notice;

DO $check$
DECLARE
  _tables    int := (SELECT count(*) FROM pg_tables WHERE schemaname = 'public');
  _functions int := (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                      WHERE n.nspname = 'public' AND p.prokind = 'f'
                        AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e'));
  _policies  int := (SELECT count(*) FROM pg_policies WHERE schemaname = 'public');
  -- community_badges is a read-only catalogue (users have SELECT only), as in production.
  _rls_off   text := (SELECT string_agg(tablename, ', ') FROM pg_tables WHERE schemaname = 'public' AND NOT rowsecurity
                       AND tablename <> 'community_badges');
  _buckets   int := (SELECT count(*) FROM storage.buckets);
  _auth_trg  int := (SELECT count(*) FROM pg_trigger WHERE tgrelid = 'auth.users'::regclass AND NOT tgisinternal
                      AND tgname IN ('on_auth_user_created', 'on_auth_user_email_verified'));
  _plans     int := (SELECT count(*) FROM public.plans);
BEGIN
  IF _tables < ${expected.tables} THEN RAISE EXCEPTION 'Install check: % tables, expected %', _tables, ${expected.tables}; END IF;
  IF _functions < ${expected.functions} THEN RAISE EXCEPTION 'Install check: % functions, expected %', _functions, ${expected.functions}; END IF;
  IF _policies < ${expected.policies} THEN RAISE EXCEPTION 'Install check: % policies, expected %', _policies, ${expected.policies}; END IF;
  IF _rls_off IS NOT NULL THEN RAISE EXCEPTION 'Install check: row security is off on: %', _rls_off; END IF;
  IF _buckets < 6 THEN RAISE EXCEPTION 'Install check: % storage buckets, expected 6', _buckets; END IF;
  IF _auth_trg < 2 THEN RAISE EXCEPTION 'Install check: auth.users triggers missing'; END IF;
  IF _plans < 1 THEN RAISE EXCEPTION 'Install check: plans not seeded'; END IF;
  RAISE NOTICE 'illuxus install OK: % tables, % functions, % policies, % buckets, % plans',
    _tables, _functions, _policies, _buckets, _plans;
END
$check$;

COMMIT;
`;

writeFileSync(join(root, "supabase/install.sql"), out);
console.log(`wrote supabase/install.sql (${out.split("\n").length} lines) — expects`, expected);
