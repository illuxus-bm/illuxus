#!/usr/bin/env node
/**
 * Writes server/functions/registry.generated.ts: one lazy import per ported
 * edge function (server/functions/<name>/index.ts). Literal import() calls,
 * so Vercel bundles every function into api/v1/fn/[name].ts.
 *
 *   node scripts/build-function-registry.mjs
 */
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = join(ROOT, "server/functions");
const names = readdirSync(DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_") && existsSync(join(DIR, d.name, "index.ts")))
  .map((d) => d.name)
  .sort();

const lines = names.map((n) => `  ${JSON.stringify(n)}: () => import("./${n}/index.js"),`);
writeFileSync(join(DIR, "registry.generated.ts"), `// GENERATED by scripts/build-function-registry.mjs. Do not edit.
import type { EdgeHandler } from "../edge/deno.js";

export const FUNCTIONS: Record<string, () => Promise<{ default: EdgeHandler }>> = {
${lines.join("\n")}
};
`);
console.log(`wrote server/functions/registry.generated.ts (${names.length} functions)`);
